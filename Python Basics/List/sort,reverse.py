## sort

nums = [5, 2, 9, 1, 7]
nums.sort()
print(nums)


fruits = ["mango", "apple", "banana"]
fruits.sort()    ## sort in alphabatical order
print(fruits)

nums = [5,2,9,1]
nums.sort(reverse=True)   ## sort in descending order
print(nums)

nums = [4,1,3]

new_list = sorted(nums)

print(nums)
print(new_list)


## Reverse List

nums = [1, 2, 3, 4, 5]
nums.reverse()
print(nums)

nums = [3,1,4,2]
nums.reverse()
print(nums)

## using Slicing

nums = [1,10,3,22]
rev = nums[::-1]
print(rev)

